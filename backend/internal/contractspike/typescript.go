package contractspike

import (
	"fmt"
	"sort"
	"strings"
)

const tsHeader = "// Code generated by backend/internal/contractspike (spike #2342); DO NOT EDIT.\n"

// TypeScript is variant 1: types and zod decoders written directly from the
// model. The helpers it imports are the handwritten contract-runtime.ts.
func TypeScript(doc Document) string {
	var out strings.Builder
	out.WriteString(tsHeader)
	out.WriteString("import { z } from \"zod\";\n")
	out.WriteString("import {\n  calendarDate,\n  instant,\n  int64String,\n  laxInt64,\n  legacyInt64,\n  paginated,\n  safeInt,\n  success,\n} from \"../contract-runtime\";\n")
	for _, object := range dependencyOrder(doc.Types) {
		fmt.Fprintf(&out, "\n/** Go: %s */\nexport interface %s {\n", object.GoType, object.Name)
		for _, field := range object.Fields {
			optional := ""
			if field.Optional {
				optional = "?"
			}
			fmt.Fprintf(&out, "  %s%s: %s;\n", field.Name, optional, tsType(field.Schema))
		}
		out.WriteString("}\n\n")
		fmt.Fprintf(&out, "export const %sSchema: z.ZodType<%s, unknown> = z.object({\n", object.Name, object.Name)
		for _, field := range object.Fields {
			decoder := zodType(field.Schema)
			if field.Optional {
				decoder += ".optional()"
			}
			fmt.Fprintf(&out, "  %s: %s,\n", field.Name, decoder)
		}
		out.WriteString("});\n")
	}
	out.WriteString("\nexport const routes = {\n")
	for _, route := range doc.Routes {
		wrap := "success"
		if route.Paginated {
			wrap = "paginated"
		}
		fmt.Fprintf(&out, "  %q: {\n    method: %q,\n    pattern: %q,\n    portals: [%s],\n", route.Method+" "+route.Pattern, route.Method, route.Pattern, quoted(route.Portals))
		if route.Variants != nil {
			fmt.Fprintf(&out, "    variantParam: %q,\n    defaultVariant: %q,\n    response: {\n", route.Variants.QueryParam, route.Variants.Default)
			for _, value := range sortedKeys(route.Variants.Cases) {
				fmt.Fprintf(&out, "      %s: %s(%s),\n", value, wrap, zodType(route.Variants.Cases[value]))
			}
			out.WriteString("    },\n")
		} else {
			fmt.Fprintf(&out, "    response: %s(%s),\n", wrap, zodType(*route.Response))
		}
		out.WriteString("  },\n")
	}
	out.WriteString("} as const;\n")
	return out.String()
}

func quoted(values []string) string {
	parts := make([]string, len(values))
	for i, value := range values {
		parts[i] = fmt.Sprintf("%q", value)
	}
	return strings.Join(parts, ", ")
}

func sortedKeys[V any](m map[string]V) []string {
	keys := make([]string, 0, len(m))
	for key := range m {
		keys = append(keys, key)
	}
	sort.Strings(keys)
	return keys
}

func tsType(s Schema) string {
	var t string
	switch s.Kind {
	case KindString, KindDate, KindInstant, KindID, KindLegacyID, KindLaxID:
		t = "string"
	case KindBool:
		t = "boolean"
	case KindInt, KindNumber:
		t = "number"
	case KindArray:
		elem := tsType(*s.Elem)
		if strings.Contains(elem, " ") {
			elem = "(" + elem + ")"
		}
		t = elem + "[]"
	case KindMap:
		t = "Record<string, " + tsType(*s.Elem) + ">"
	case KindRef:
		t = s.Ref
	}
	if s.Nullable {
		t += " | null"
	}
	return t
}

func zodType(s Schema) string {
	var z string
	switch s.Kind {
	case KindString:
		z = "z.string()"
	case KindBool:
		z = "z.boolean()"
	case KindInt:
		z = "safeInt"
	case KindNumber:
		z = "z.number()"
	case KindID:
		z = "int64String"
	case KindLegacyID:
		z = "legacyInt64"
	case KindLaxID:
		z = "laxInt64"
	case KindDate:
		z = "calendarDate"
	case KindInstant:
		z = "instant"
	case KindArray:
		z = "z.array(" + zodType(*s.Elem) + ")"
	case KindMap:
		z = "z.record(z.string(), " + zodType(*s.Elem) + ")"
	case KindRef:
		z = s.Ref + "Schema"
	}
	if s.Nullable {
		z += ".nullable()"
	}
	return z
}

// dependencyOrder puts a type after the types it refers to: a zod schema is a
// value and must exist before its first use. A cycle would need z.lazy and is
// rejected by the walker today (it never terminates the name lookup with a
// finished object), so the spike does not handle it.
func dependencyOrder(types []Object) []Object {
	byName := map[string]Object{}
	for _, object := range types {
		byName[object.Name] = object
	}
	var ordered []Object
	done := map[string]bool{}
	var visit func(name string)
	var refs func(s Schema)
	refs = func(s Schema) {
		if s.Kind == KindRef {
			visit(s.Ref)
		}
		if s.Elem != nil {
			refs(*s.Elem)
		}
	}
	visit = func(name string) {
		if done[name] {
			return
		}
		done[name] = true
		for _, field := range byName[name].Fields {
			refs(field.Schema)
		}
		ordered = append(ordered, byName[name])
	}
	for _, object := range types {
		visit(object.Name)
	}
	return ordered
}
