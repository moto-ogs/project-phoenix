const tsHeader = "// Code generated by `go run . gencontract` (backend); DO NOT EDIT.\n"

// TypeScript writes one file per route resource, keyed by file name. The
// files import the handwritten runtime.ts next to them. A type or enum that
// two resources use is written once, in shared.generated.ts, and imported.
func TypeScript(doc Document) (map[string]string, error) {
	byName := map[string]Object{}
	for _, object := range doc.Types {
		byName[object.Name] = object
	}
	enums := map[string]Enum{}
	for _, enum := range doc.Enums {
		enums[enum.Name] = enum
	}
	resources := map[string][]Route{}
	for _, route := range doc.Routes {
		resources[resourceOf(route.Pattern)] = append(resources[resourceOf(route.Pattern)], route)
	}
	for _, reserved := range []string{portalsFile, sharedFile, browserTraitsFile, "problem-details.generated.ts", "stream-event.generated.ts", "partial-results.generated.ts"} {
		if _, taken := resources[strings.TrimSuffix(reserved, ".generated.ts")]; taken {
			return nil, fmt.Errorf("the resource name %q is taken by a generated table", strings.TrimSuffix(reserved, ".generated.ts"))
		}
	}
	newWriter := func() *tsWriter {
		return &tsWriter{byName: byName, enums: enums, done: map[string]bool{}, helpers: map[string]bool{}}
	}
	writers := map[string]*tsWriter{}
	users := map[string]int{}
	for resource, routes := range resources {
		writers[resource] = newWriter()
		writers[resource].visitRoutes(routes, users)
	}
	// A type two resources use takes everything it refers to along: both
	// resources visited those too. Each resource lists a type after the ones
	// it refers to, so the shared file keeps that order.
	shared := newWriter()
	for _, resource := range sortedKeys(resources) {
		w := writers[resource]
		w.typeOrder = shared.take(w.typeOrder, "", users)
		w.enumOrder = shared.take(w.enumOrder, "enum:", users)
	}
	files := map[string]string{
		portalsFile: portalTable(resources), browserTraitsFile: browserTraits(doc),
	}
	for resource, routes := range resources {
		files[resource+".generated.ts"] = writers[resource].file(routes, shared)
	}
	if len(shared.typeOrder)+len(shared.enumOrder) > 0 {
		files[sharedFile] = shared.file(nil, nil)
	}
	writeNonRouteFiles(files, doc, newWriter)
	writePartialResults(files, doc.Routes, newWriter())
	return files, nil
}

func writePartialResults(files map[string]string, routes []Route, writer *tsWriter) {
	writer.browser = true
	var entries strings.Builder
	for _, route := range routes {
		if route.PartialError == "" {
			continue
		}
		writer.visit(*route.Response)
		fmt.Fprintf(&entries, "  %q: partialResult<%s>(%s),\n", route.Key(), writer.tsType(*route.Response, false), writer.field(*route.Response))
	}
	if entries.Len() > 0 {
		writer.helpers["partialResult"] = true
		files["partial-results.generated.ts"] = writer.file(nil, nil) +
			"\nexport const partialResults = {\n" + entries.String() + "} as const;\n"
	}
}

func writeNonRouteFiles(files map[string]string, doc Document, newWriter func() *tsWriter) {
	if len(doc.ProblemDetails) > 0 {
		writer := newWriter()
		writer.browser = true
		var decoders strings.Builder
		decoders.WriteString("\nexport const problemDetails = {\n")
		for _, code := range sortedKeys(doc.ProblemDetails) {
			schema := doc.ProblemDetails[code]
			writer.visit(schema)
			fmt.Fprintf(&decoders, "  %q: %s,\n", code, writer.field(schema))
		}
		decoders.WriteString("} as const;\n")
		files["problem-details.generated.ts"] = writer.file(nil, nil) + decoders.String()
	}
	if doc.StreamEvent != nil {
		writer := newWriter()
		writer.browser = true
		writer.visit(*doc.StreamEvent)
		files["stream-event.generated.ts"] = writer.file(nil, nil)
	}
}

// visitRoutes orders the types of a resource's routes and counts the
// resource as a user of each.
func (w *tsWriter) visitRoutes(routes []Route, users map[string]int) {
	for _, route := range routes {
		for _, schema := range routeSchemas(route) {
			w.visit(schema)
		}
	}
	for _, name := range w.typeOrder {
		users[name]++
	}
	for _, name := range w.enumOrder {
		users["enum:"+name]++
	}
}

// take moves the names more than one resource uses from a resource's order
// into the shared writer's and returns the rest.
func (w *tsWriter) take(names []string, prefix string, users map[string]int) []string {
	var own []string
	for _, name := range names {
		if users[prefix+name] < 2 {
			own = append(own, name)
			continue
		}
		if w.done[prefix+name] {
			continue
		}
		w.done[prefix+name] = true
		if prefix == "" {
			w.typeOrder = append(w.typeOrder, name)
		} else {
			w.enumOrder = append(w.enumOrder, name)
		}
	}
	return own
}

const sharedFile = "shared.generated.ts"

const portalsFile = "portals.generated.ts"

const browserTraitsFile = "browser-traits.generated.ts"

// browserTraits carries only routing facts; importing it never ships decoders.
func browserTraits(doc Document) string {
	routes := doc.Routes
	var out strings.Builder
	out.WriteString(tsHeader)
	paths := map[string][]string{}
	for _, route := range routes {
		if route.BrowserPath != "" {
			for _, portal := range route.Portals {
				paths[portal] = append(paths[portal], fmt.Sprintf("%q: %q", route.Key(), route.BrowserPath))
			}
		}
	}
	out.WriteString("\nexport const browserRoutePaths = {\n")
	for _, portal := range sortedKeys(paths) {
		fmt.Fprintf(&out, "  %s: {\n", portal)
		for _, entry := range paths[portal] {
			fmt.Fprintf(&out, "    %s,\n", entry)
		}
		out.WriteString("  },\n")
	}
	out.WriteString("} as const;\n")
	writeAccountLogoutBrowserPaths(&out, routes)
	writeRouteSet(&out, "noCommitRoutes", routes, func(route Route) bool {
		return route.NoCommit != ""
	})
	writeRouteSet(&out, "tenantNoRetryRoutes", routes, func(route Route) bool {
		return route.NoRetryAfterRenewal != "" && slices.Contains(route.Portals, "tenant")
	})
	objects := make(map[string]Object, len(doc.Types))
	for _, object := range doc.Types {
		objects[object.Name] = object
	}
	writeRouteSet(&out, "studentPhotoRoutes", routes, func(route Route) bool {
		return slices.Contains(route.Portals, "tenant") && slices.ContainsFunc(routeSchemas(route), func(schema Schema) bool {
			return carriesPhotoVersion(schema, objects, map[string]bool{})
		})
	})
	fmt.Fprintf(&out, "\nexport const publicAssetCache = %q;\n", contractmodel.FileCachePublicAsset)
	out.WriteString("\nexport const fileCacheValues = new Set<string>([\n")
	for _, value := range contractmodel.FileCacheValues {
		fmt.Fprintf(&out, "  %q,\n", value)
	}
	out.WriteString("]);\n")
	return out.String()
}

// Only these responses need a BFF compatibility alias for old browser tabs.
func carriesPhotoVersion(schema Schema, objects map[string]Object, seen map[string]bool) bool {
	if schema.Elem != nil {
		return carriesPhotoVersion(*schema.Elem, objects, seen)
	}
	if schema.Kind != KindRef || seen[schema.Ref] {
		return false
	}
	seen[schema.Ref] = true
	for _, field := range objects[schema.Ref].Fields {
		if field.Name == "photo_version" || carriesPhotoVersion(field.Schema, objects, seen) {
			return true
		}
	}
	return false
}

// These browser routes revoke portal-specific sessions through the same Go route.
func writeAccountLogoutBrowserPaths(out *strings.Builder, routes []Route) {
	for _, route := range routes {
		if route.Key() != "POST /auth/logout" {
			continue
		}
		out.WriteString("\nexport const accountLogoutBrowserPaths = {\n")
		for _, portal := range []string{"caterer", "parent", "school", "traeger"} {
			fmt.Fprintf(out, "  %s: %q,\n", portal, "/api/"+portal+route.Pattern)
		}
		out.WriteString("} as const;\n")
		return
	}
}

func writeRouteSet(out *strings.Builder, name string, routes []Route, matches func(Route) bool) {
	keys := map[string]bool{}
	for _, route := range routes {
		if matches(route) {
			keys[route.Key()] = true
		}
	}
	fmt.Fprintf(out, "\nexport const %s = new Set<string>([\n", name)
	for _, key := range sortedKeys(keys) {
		fmt.Fprintf(out, "  %q,\n", key)
	}
	out.WriteString("]);\n")
}

// portalTable writes the routes each portal may reach: the allowlist of a
// portal's proxy. A route that names no portal is in no list. A route its
// portal's own route file serves stands in routeFileRoutes instead, never
// in the allowlist (#7808).
func portalTable(resources map[string][]Route) string {
	byPortal := map[string][]string{}
	byRouteFile := map[string][]string{}
	var out strings.Builder
	out.WriteString(tsHeader)
	for _, resource := range sortedKeys(resources) {
		fmt.Fprintf(&out, "import { routes as %s } from \"./%s.generated\";\n", resourceAlias(resource), resource)
		for _, route := range resources[resource] {
			table := byPortal
			if route.RouteFile != "" {
				table = byRouteFile
			}
			for _, portal := range route.Portals {
				table[portal] = append(table[portal], fmt.Sprintf("%s[%q]", resourceAlias(resource), route.Key()))
			}
		}
	}
	writeTable(&out, "The registered routes of each portal, by the scope of its session token.", "portalRoutes", byPortal)
	writeTable(&out, "The routes each portal's own route files serve; its proxy serves none of them.", "routeFileRoutes", byRouteFile)
	return out.String()
}

func writeTable(out *strings.Builder, doc, name string, byPortal map[string][]string) {
	fmt.Fprintf(out, "\n/** %s */\nexport const %s = {\n", doc, name)
	for _, portal := range sortedKeys(byPortal) {
		fmt.Fprintf(out, "  %s: [\n", portal)
		for _, entry := range byPortal[portal] {
			fmt.Fprintf(out, "    %s,\n", entry)
		}
		out.WriteString("  ],\n")
	}
	out.WriteString("} as const;\n")
}

// resourceAlias turns parent-me into parentMe.
func resourceAlias(resource string) string {
	parts := strings.Split(resource, "-")
	for i := 1; i < len(parts); i++ {
		parts[i] = upperFirst(parts[i])
	}
	alias := strings.Join(parts, "")
	// A resource such as /api/import names a reserved word, which the import
	// of portals.generated.ts cannot bind.
	if reservedWords[alias] {
		return alias + "Routes"
	}
	return alias
}

// reservedWords are the ECMAScript words an import binding may not take.
var reservedWords = map[string]bool{
	"await": true, "break": true, "case": true, "catch": true, "class": true, "const": true,
	"continue": true, "debugger": true, "default": true, "delete": true, "do": true, "else": true,
	"enum": true, "export": true, "extends": true, "false": true, "finally": true, "for": true,
	"function": true, "if": true, "implements": true, "import": true, "in": true, "instanceof": true,
	"interface": true, "let": true, "new": true, "null": true, "package": true, "private": true,
	"protected": true, "public": true, "return": true, "static": true, "super": true, "switch": true,
	"this": true, "throw": true, "true": true, "try": true, "typeof": true, "var": true,
	"void": true, "while": true, "with": true, "yield": true,
}

func routeSchemas(r Route) []Schema {
	var schemas []Schema
	if r.Request != nil {
		schemas = append(schemas, *r.Request)
	}
	if r.Response != nil {
		schemas = append(schemas, *r.Response)
	}
	if r.Variants != nil {
		for _, value := range sortedKeys(r.Variants.Cases) {
			schemas = append(schemas, r.Variants.Cases[value])
		}
	}
	return schemas
}

// resourceOf names the generated file of a route: the path segment below
// /api, or the first two segments elsewhere.
func resourceOf(pattern string) string {
	parts := strings.Split(strings.Trim(pattern, "/"), "/")
	if parts[0] == "api" && len(parts) > 1 {
		return parts[1]
	}
	if len(parts) > 1 && !strings.ContainsAny(parts[1], "{*}") {
		return parts[0] + "-" + parts[1]
	}
	return parts[0]
}

type tsWriter struct {
	byName    map[string]Object
	enums     map[string]Enum
	done      map[string]bool
	helpers   map[string]bool
	typeOrder []string
	enumOrder []string
	// Non-route decoders run in browsers and must not bring the route runtime.
	browser bool
	// pending names the types of the file not written yet: a reference to one
	// of them closes a cycle and is read lazily.
	pending map[string]bool
}

// visit orders the types so that a schema exists before its first use.
func (w *tsWriter) visit(s Schema) {
	if s.Elem != nil {
		w.visit(*s.Elem)
	}
	if s.Kind == KindEnum && !w.done["enum:"+s.Ref] {
		w.done["enum:"+s.Ref] = true
		w.enumOrder = append(w.enumOrder, s.Ref)
	}
	if s.Kind != KindRef || w.done[s.Ref] {
		return
	}
	w.done[s.Ref] = true
	for _, field := range w.byName[s.Ref].Fields {
		w.visit(field.Schema)
	}
	w.typeOrder = append(w.typeOrder, s.Ref)
}

// file writes a resource's types, queries and routes, or with no routes the
// shared types alone. It imports from shared what the text names.
func (w *tsWriter) file(routes []Route, shared *tsWriter) string {
	var body strings.Builder
	sort.Strings(w.enumOrder)
	for _, name := range w.enumOrder {
		fmt.Fprintf(&body, "\nexport const %s = [%s] as const;\nexport type %s = (typeof %s)[number];\n", enumConst(name), quoted(w.enums[name].Values), name, enumConst(name))
	}
	w.pending = make(map[string]bool, len(w.typeOrder))
	for _, name := range w.typeOrder {
		w.pending[name] = true
	}
	for _, name := range w.typeOrder {
		w.object(&body, w.byName[name])
		delete(w.pending, name)
	}
	if routes != nil {
		body.WriteString("\nexport const routes = {\n")
		for _, route := range routes {
			w.route(&body, route)
		}
		body.WriteString("} as const;\n")
	}

	var out strings.Builder
	out.WriteString(tsHeader)
	runtime := "runtime"
	if w.browser {
		runtime = "browser-runtime"
	}
	if strings.Contains(body.String(), "z.") {
		out.WriteString("import { z } from \"zod\";\n")
	}
	if helpers := sortedKeys(w.helpers); len(helpers) > 0 {
		fmt.Fprintf(&out, "import {\n  %s,\n} from \"./%s\";\n", strings.Join(helpers, ",\n  "), runtime)
	}
	if imports := shared.namedIn(body.String()); len(imports) > 0 {
		fmt.Fprintf(&out, "import {\n  %s,\n} from \"./%s\";\n", strings.Join(imports, ",\n  "), strings.TrimSuffix(sharedFile, ".ts"))
	}
	out.WriteString(body.String())
	return out.String()
}

// namedIn lists the shared names a file's text uses, as import specifiers.
func (w *tsWriter) namedIn(text string) []string {
	if w == nil {
		return nil
	}
	var imports []string
	add := func(name, specifier string) {
		if regexp.MustCompile(`\b` + name + `\b`).MatchString(text) {
			imports = append(imports, specifier)
		}
	}
	for _, name := range w.enumOrder {
		add(enumConst(name), enumConst(name))
		add(name, "type "+name)
	}
	for _, name := range w.typeOrder {
		add(name, "type "+name)
		add(name+"Schema", name+"Schema")
	}
	sort.Strings(imports)
	return imports
}

func (w *tsWriter) object(out *strings.Builder, object Object) {
	fmt.Fprintf(out, "\n/** Go: %s */\nexport interface %s {\n", object.GoType, object.Name)
	for _, field := range object.Fields {
		if field.Deprecated {
			out.WriteString("  /** @deprecated leaves the contract with the next release */\n")
		}
		fmt.Fprintf(out, "  %s%s: %s;\n", field.Name, optionalMark(field.Optional), w.tsType(field.Schema, object.Request))
	}
	out.WriteString("}\n")
	if object.Request {
		return
	}
	// The interface above and this shape come from one model; `object` hands
	// the checker the interface instead of letting it derive the shape's type.
	w.helpers["object"] = true
	codecType := "z.ZodType<" + object.Name + ", unknown>"
	pure := ""
	if w.browser {
		w.helpers["type Decoder"] = true
		codecType = "Decoder<" + object.Name + ">"
		pure = "/*#__PURE__*/ "
	}
	fmt.Fprintf(out, "\nexport const %sSchema: %s = %sobject<%s>({\n", object.Name, codecType, pure, object.Name)
	for _, field := range object.Fields {
		decoder := w.field(field.Schema)
		if field.Optional {
			w.helpers["optional"] = true
			decoder = pure + "optional(" + decoder + ")"
		}
		fmt.Fprintf(out, "  %s: %s,\n", field.Name, decoder)
	}
	out.WriteString("});\n")
}

// writeQuery emits metadata, not validators: the proxy only reads the keys.
func writeQuery(out *strings.Builder, route Route) {
	if len(route.Query) == 0 {
		return
	}
	out.WriteString("    query: {\n")
	for _, param := range route.Query {
		fmt.Fprintf(out, "      %q: { kind: %q", param.Name, param.Kind)
		if param.Repeated {
			out.WriteString(", repeated: true")
		}
		if len(param.Values) > 0 {
			fmt.Fprintf(out, ", values: [%s]", quoted(param.Values))
		}
		out.WriteString(" },\n")
	}
	out.WriteString("    },\n")
}

// envelopeHelper names the runtime helper of the route's answer.
func envelopeHelper(route Route) string {
	switch {
	case route.File:
		return "fileAnswer"
	case route.NoData:
		return "noData"
	case route.Paginated:
		return "paginated"
	}
	return "success"
}

func (w *tsWriter) route(out *strings.Builder, route Route) {
	fmt.Fprintf(out, "  %q: {\n    method: %q,\n    pattern: %q,\n    portals: [%s],\n", route.Key(), route.Method, route.Pattern, quoted(route.Portals))
	if route.Deprecated {
		out.WriteString("    deprecated: true,\n")
	}
	if route.NoRetryAfterRenewal != "" {
		fmt.Fprintf(out, "    noRetryAfterRenewal: %q,\n", route.NoRetryAfterRenewal)
	}
	if route.NoCommit != "" {
		fmt.Fprintf(out, "    noCommit: %q,\n", route.NoCommit)
	}
	if route.MaxBodyBytes > 0 {
		fmt.Fprintf(out, "    maxBodyBytes: %d,\n", route.MaxBodyBytes)
	}
	if route.TooLargeCode != "" {
		fmt.Fprintf(out, "    tooLargeCode: %q,\n", route.TooLargeCode)
	}
	if route.PublicFile != "" {
		fmt.Fprintf(out, "    publicFile: %q,\n", route.PublicFile)
	}
	if route.PublicUpload != "" {
		fmt.Fprintf(out, "    publicUpload: %q,\n", route.PublicUpload)
	}
	if route.FileCache != "" {
		fmt.Fprintf(out, "    fileCache: %q,\n", route.FileCache)
	}
	if route.ConditionalGet {
		out.WriteString("    conditionalGet: true,\n")
	}
	if route.PrivateCache {
		out.WriteString("    privateCache: true,\n")
	}
	writeRouteFileTraits(out, route)
	writeQuery(out, route)
	if route.Multipart {
		w.helpers["multipart"] = true
		out.WriteString("    request: multipart,\n")
	}
	if route.Request != nil {
		w.helpers["requestBody"] = true
		fmt.Fprintf(out, "    request: requestBody<%s>(),\n", w.tsType(*route.Request, true))
	}
	w.response(out, route)
	out.WriteString("  },\n")
}

// writeRouteFileTraits writes the traits of a route its portal's own route file
// serves (#7808).
func writeRouteFileTraits(out *strings.Builder, route Route) {
	if route.RouteFile != "" {
		fmt.Fprintf(out, "    routeFile: %q,\n", route.RouteFile)
		if route.BrowserPath != "" {
			fmt.Fprintf(out, "    browserPath: %q,\n", route.BrowserPath)
		}
		if route.BrowserMethod != "" {
			fmt.Fprintf(out, "    browserMethod: %q,\n", route.BrowserMethod)
		}
		if route.BrowserOwnContract {
			out.WriteString("    browserOwnContract: true,\n")
		}
	}
	if route.Plain {
		out.WriteString("    plain: true,\n")
	}
}

// response writes the route's answer: a decoder, the decoders of its
// variants, or the marker of an answer without data.
func (w *tsWriter) response(out *strings.Builder, route Route) {
	if route.Plain {
		// The data is the whole body.
		fmt.Fprintf(out, "    response: %s,\n", w.zod(*route.Response))
		return
	}
	wrap := envelopeHelper(route)
	w.helpers[wrap] = true
	if route.Variants != nil {
		fmt.Fprintf(out, "    variantParam: %q,\n    defaultVariant: %q,\n    response: {\n", route.Variants.QueryParam, route.Variants.Default)
		for _, value := range sortedKeys(route.Variants.Cases) {
			fmt.Fprintf(out, "      %s: %s(%s),\n", value, wrap, w.zod(route.Variants.Cases[value]))
		}
		out.WriteString("    },\n")
	} else if route.NoData || route.File {
		fmt.Fprintf(out, "    response: %s,\n", wrap)
	} else {
		fmt.Fprintf(out, "    response: %s(%s),\n", wrap, w.zod(*route.Response))
	}
}

func optionalMark(optional bool) string {
	if optional {
		return "?"
	}
	return ""
}

func upperFirst(s string) string { return strings.ToUpper(s[:1]) + s[1:] }

// enumConst turns DepartureMode into DEPARTURE_MODE_VALUES.
func enumConst(name string) string {
	var out strings.Builder
	for i, r := range name {
		if i > 0 && unicode.IsUpper(r) {
			out.WriteByte('_')
		}
		out.WriteRune(unicode.ToUpper(r))
	}
	return out.String() + "_VALUES"
}

func quoted(values []string) string {
	parts := make([]string, len(values))
	for i, value := range values {
		parts[i] = fmt.Sprintf("%q", value)
	}
	return strings.Join(parts, ", ")
}

func sortedKeys[V any](m map[string]V) []string {
	keys := make([]string, 0, len(m))
	for key := range m {
		keys = append(keys, key)
	}
	sort.Strings(keys)
	return keys
}

// tsType is the type a decoder hands out or, for a request, the type the
// client sends. An identifier is a string both ways.
func (w *tsWriter) tsType(s Schema, request bool) string {
	var t string
	switch s.Kind {
	case KindString, KindDate, KindInstant, KindClock, KindID:
		t = "string"
	case KindBool:
		t = "boolean"
	case KindInt, KindNumber:
		t = "number"
	case KindEnum:
		w.helpers["type OpenEnum"] = true
		t = "OpenEnum<" + s.Ref + ">"
	case KindArray:
		elem := w.tsType(*s.Elem, request)
		if strings.Contains(elem, " ") {
			elem = "(" + elem + ")"
		}
		t = elem + "[]"
	case KindMap:
		t = "Record<string, " + w.tsType(*s.Elem, request) + ">"
	case KindJSON:
		t = "unknown"
	case KindRef:
		t = s.Ref
	}
	if s.LegacyJSON {
		w.helpers["type LegacyJSON"] = true
		return t + " | LegacyJSON"
	}
	if s.Nullable {
		t += " | null"
	}
	return t
}

// field is the decoder of a value inside a generated shape. The interface
// next to the shape says what it yields, so every combinator is an untyped
// helper of the runtime: the checker derives nothing per field.
func (w *tsWriter) field(s Schema) string {
	helper := func(name string) string {
		w.helpers[name] = true
		return name
	}
	var z string
	call := func(name, value string) string {
		prefix := ""
		if w.browser {
			prefix = "/*#__PURE__*/ "
		}
		return prefix + helper(name) + "(" + value + ")"
	}
	switch s.Kind {
	case KindString, KindEnum:
		// An open enum decodes any string.
		z = helper("str")
	case KindBool:
		z = helper("bool")
	case KindInt:
		z = helper("safeInt")
	case KindNumber:
		z = helper("num")
	case KindID:
		z = helper("int64String")
		if s.NoID {
			z += ".orNone"
		}
	case KindDate:
		z = helper("calendarDate")
	case KindInstant:
		z = helper("instant")
	case KindClock:
		z = helper("clockTime")
	case KindArray:
		z = call("arr", w.field(*s.Elem))
	case KindMap:
		z = call("rec", w.field(*s.Elem))
	case KindJSON:
		z = helper("json")
	case KindRef:
		z = s.Ref + "Schema"
		if w.pending[s.Ref] {
			// A type that refers back to itself or to a type of its cycle
			// reads that schema once it exists.
			z = call("lazy", "() => "+z)
		}
	}
	if s.Nullable {
		z = call("nullable", z)
	}
	if s.LegacyJSON {
		return call("legacyJSON", z)
	}
	return z
}

// zod is the typed decoder of a route's answer: its type is what the client
// reads, so it is derived here and only here.
func (w *tsWriter) zod(s Schema) string {
	helper := func(name string) string {
		w.helpers[name] = true
		return name
	}
	var z string
	switch s.Kind {
	case KindString:
		z = "z.string()"
	case KindBool:
		z = "z.boolean()"
	case KindInt:
		z = helper("safeInt")
	case KindNumber:
		z = "z.number()"
	case KindID:
		z = helper("int64String")
		if s.NoID {
			z = helper("int64StringOrNone")
		}
	case KindDate:
		z = helper("calendarDate")
	case KindInstant:
		z = helper("instant")
	case KindClock:
		z = helper("clockTime")
	case KindEnum:
		z = "z.string()"
	case KindArray:
		z = "z.array(" + w.zod(*s.Elem) + ")"
	case KindMap:
		z = "z.record(z.string(), " + w.zod(*s.Elem) + ")"
	case KindJSON:
		z = "z.unknown()"
	case KindRef:
		z = s.Ref + "Schema"
		if w.pending[s.Ref] {
			// A type that refers back to itself or to a type of its cycle
			// reads that schema once it exists.
			z = "z.lazy(() => " + z + ")"
		}
	}
	if s.Nullable {
		z += ".nullable()"
	}
	return z
}
