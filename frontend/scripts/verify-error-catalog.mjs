import { readFile, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import { format, resolveConfig } from "prettier";
import { ERROR_CLASSES, readRegistry } from "../../scripts/error-registry.mjs";
import { readLocaleMessages } from "./message-sources.mjs";

const registry = readRegistry();
const locales = JSON.parse(
  await readFile(
    new URL(
      "../../backend/modules/delivery/internal/adapters/localization/locales.json",
      import.meta.url,
    ),
    "utf8",
  ),
);
// Portals whose readers turn to someone else than the school. Each lists the
// classes whose fallback names that contact (#6871).
const portalClasses = { traeger: ["permission"] };
// Placeholders `presentError` fills in itself: the object of the failed
// action and the school's care term (`enrollment.care_facility_term`) with
// its declined German forms (`{careAcc}`, `{careNomCap}`, …, #8136). The
// tests in `care-facility-term-value.test.ts` check these names against the
// values the frontend supplies.
const FRONTEND_PARAMETERS = ["object"];
const CARE_TERM_PARAMETER = /^care[A-Z][A-Za-z]*$/;
const failures = [];
const runtimeCatalog = {};
let germanLogoutNotice;

for (const { code: locale } of locales) {
  const messages = readLocaleMessages(locale);
  const catalog = messages.errorCatalog;
  const codes = catalog?.codes ?? {};
  const overrides = {};
  if (locale === "de") germanLogoutNotice = codes.identity?.logout_not_revoked;

  for (const entry of registry.codes) {
    const [area, name] = entry.code.split(".");
    const text = codes[area]?.[name];
    if (typeof text !== "string" || !text.trim()) {
      failures.push(`${locale}: ${entry.code}: missing text`);
      continue;
    }
    // `object` and the care term come from the frontend (#6258): registry
    // parameters are snake_case, so a backend value cannot take their place.
    const allowedParameters = new Set([
      ...FRONTEND_PARAMETERS,
      ...entry.parameters,
    ]);
    for (const match of text.matchAll(/\{([^{}]+)\}/g)) {
      if (
        !allowedParameters.has(match[1]) &&
        !CARE_TERM_PARAMETER.test(match[1])
      ) {
        failures.push(
          `${locale}: ${entry.code}: unsupported parameter ${match[1]}`,
        );
      }
    }
    if (text !== catalog?.classes?.[entry.class]) {
      overrides[entry.code] = text;
    }
  }

  const registered = new Set(registry.codes.map((entry) => entry.code));
  for (const [area, entries] of Object.entries(codes)) {
    for (const name of Object.keys(entries)) {
      if (!registered.has(`${area}.${name}`)) {
        failures.push(`${locale}: ${area}.${name}: not in registry`);
      }
    }
  }
  for (const className of ERROR_CLASSES) {
    if (!catalog?.classes?.[className]?.trim()) {
      failures.push(`${locale}: ${className}: missing class fallback`);
    }
  }
  for (const action of [
    "retry",
    "copyRequestId",
    "requestId",
    "crash",
    "fieldCheck",
  ]) {
    if (
      typeof catalog?.actions?.[action] !== "string" ||
      !catalog.actions[action].trim()
    ) {
      failures.push(`${locale}: ${action}: missing action text`);
    }
  }
  for (const [portal, classNames] of Object.entries(portalClasses)) {
    const texts = catalog?.portalClasses?.[portal] ?? {};
    for (const className of classNames) {
      if (typeof texts[className] !== "string" || !texts[className].trim()) {
        failures.push(
          `${locale}: ${portal}.${className}: missing portal class`,
        );
      }
    }
    for (const className of Object.keys(texts)) {
      if (!classNames.includes(className)) {
        failures.push(
          `${locale}: ${portal}.${className}: unknown portal class`,
        );
      }
    }
  }
  for (const portal of Object.keys(catalog?.portalClasses ?? {})) {
    if (!(portal in portalClasses)) {
      failures.push(`${locale}: ${portal}: unknown portal`);
    }
  }
  runtimeCatalog[locale] = {
    classes: catalog?.classes,
    portalClasses: catalog?.portalClasses,
    actions: catalog?.actions,
    codes: overrides,
  };
}

if (failures.length) {
  throw new Error(`Error catalog is incomplete:\n${failures.join("\n")}`);
}

// The password form needs one resolved sentence before any request fails.
if (typeof germanLogoutNotice !== "string" || /[{}]/.test(germanLogoutNotice)) {
  throw new Error(
    "The German identity.logout_not_revoked notice must be a complete sentence without parameters.",
  );
}

for (const [filename, declaration] of [
  [
    "error-catalog.generated.ts",
    `export const ERROR_CATALOG = ${JSON.stringify(runtimeCatalog, null, 2)} as const;`,
  ],
  [
    "logout-notice.generated.ts",
    `export const LOGOUT_NOT_REVOKED_NOTICE = ${JSON.stringify(germanLogoutNotice)};`,
  ],
]) {
  const path = fileURLToPath(
    new URL(`../src/lib/${filename}`, import.meta.url),
  );
  const generated = await format(
    `// Code generated by scripts/verify-error-catalog.mjs --write; DO NOT EDIT.\n${declaration}\n`,
    { ...(await resolveConfig(path)), filepath: path },
  );
  if (process.argv.includes("--write")) {
    await writeFile(path, generated);
  } else if ((await readFile(path, "utf8").catch(() => "")) !== generated) {
    throw new Error(
      `${filename} is out of date. Run pnpm generate:error-catalog.`,
    );
  }
}
